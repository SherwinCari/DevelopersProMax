
"""Home: eligibility form, verdict cards, and the AI explanation panel.

UI only. All verdicts come from ``rules.evaluate``; ``advisor`` merely
phrases them.
"""
from __future__ import annotations

import streamlit as st

import advisor
import ui_theme as ui
from data.programs import GRADE_MAX, GRADE_MIN, SHS_TRACKS, UMCETTier, all_programs
from rules import ProgramResult, Status, StudentInput, evaluate

_PROGRAMS = {p.name: p for p in all_programs()}
_TIERS = UMCETTier.ordered_labels()

_EXAMPLES = {
    "Clear pass": dict(gwa="90", math="91", eng="89", track="STEM", pending=False, tier="Average"),
    "Short by 1 point": dict(gwa="88", math="84", eng="88", track="STEM", pending=False, tier="Average"),
    "Diploma path": dict(gwa="82", math="80", eng="81", track="ABM", pending=False, tier="Below Average"),
}


def _load_example(name: str) -> None:
    ex = _EXAMPLES[name]
    st.session_state.update(
        in_gwa=ex["gwa"], in_math=ex["math"], in_eng=ex["eng"], in_track=ex["track"],
        in_pending=ex["pending"], in_tier=ex["tier"],
    )
    st.session_state.pop("hg_eval", None)


def _parse(label: str, raw: str) -> tuple[float | None, str | None]:
    raw = (raw or "").strip()
    if not raw:
        return None, f"Enter your {label}."
    try:
        val = float(raw)
    except ValueError:
        return None, f"{label} must be a number, e.g. 88."
    if not GRADE_MIN <= val <= GRADE_MAX:
        return None, f"{label} must be between {GRADE_MIN:g} and {GRADE_MAX:g}."
    return val, None


def _card_for(res: ProgramResult, focus: bool) -> None:
    p = res.program
    failed = {g.field for g in res.gaps}
    ok, wait = [], []
    for fld, req in (("GWA", p.gwa_min), ("Math", p.math_min), ("English", p.english_min)):
        if req is not None and fld not in failed:
            ok.append(f"{fld} meets the {req:g} requirement")
    if p.umcet_min_tier is not None and "UMCET" not in failed:
        if res.status is Status.PENDING_UMCET:
            wait.append(f"Awaiting UMCET result (needs {p.umcet_min_tier.label} or higher)")
        else:
            ok.append(f"UMCET meets {p.umcet_min_tier.label} or higher")
    kind = {Status.QUALIFIED: "pass", Status.PENDING_UMCET: "near", Status.NOT_QUALIFIED: "fail"}[res.status]
    meta = p.type.label
    if p.preferred_track and not res.preferred_track_met:
        meta += f" · Preferred SHS strand: {' / '.join(p.preferred_track)} (informational, not required)"
    ui.render_result_card(p.name, meta, kind, ok, wait, [g.message for g in res.gaps], focus)


def _results_panel(data: dict) -> None:
    results: list[ProgramResult] = data["results"]
    focus_code = _PROGRAMS[data["focus"]].code
    st.markdown("#### Your results")
    ordered = sorted(results, key=lambda r: r.program.code != focus_code)
    for r in ordered:
        _card_for(r, focus=r.program.code == focus_code)

    src = "Generated by your local Ollama model" if data["used_ai"] else (
        "Local AI unavailable — showing a built-in explanation instead"
    )
    ui.render_advisor(
        "Advisor explanation",
        data["explanation"],
        f"{src}. The verdict above comes from the rule engine, not the AI. "
        "Cutoffs are demonstration data — confirm with the UMak Admissions Office.",
    )
    focus_res = next(r for r in results if r.program.code == focus_code)
    if focus_res.status is Status.QUALIFIED:
        with st.expander(f"Topics to review for {focus_res.program.name}"):
            # Added: show skeleton while review topics are generated.
            loading = st.empty()
            with loading.container():
                ui.render_skeleton(lines=3, title="Preparing review topics")
                st.caption("Finding topics that may help you prepare…")

            topics = advisor.recommend_review(data["student"], focus_res.program)

            loading.empty()
            st.markdown(topics)


def render() -> None:
    ui.render_topbar()
    ui.render_header(local_ai=st.session_state.get("hg_ai_up", True))
    ui.page_header(
        "Find out if you qualify for CCIS",
        "Enter your grades, get a clear verdict in seconds, and an explanation in plain language.",
    )
    ui.render_banner(
        "Prototype: admission criteria below are <strong>demonstration data</strong>, "
        "not official UMak requirements."
    )

    left, right = st.columns([1, 1], gap="large")
    with left:
        with st.container(border=True):
            st.markdown("#### Check your eligibility")
            st.caption(f"Use your Senior High School grades ({GRADE_MIN:g}–{GRADE_MAX:g} scale).")
            program = st.selectbox("Program", list(_PROGRAMS), key="in_program")
            c1, c2 = st.columns(2)
            gwa = c1.text_input("General weighted average", placeholder="e.g. 88", key="in_gwa")
            math = c2.text_input("Math grade", placeholder="e.g. 86", key="in_math")
            c3, c4 = st.columns(2)
            eng = c3.text_input("English grade", placeholder="e.g. 85", key="in_eng")
            track = c4.selectbox("SHS strand", SHS_TRACKS, key="in_track")
            pending = st.toggle("I haven't received my UMCET result yet", key="in_pending")
            tier = st.selectbox(
                "UMCET rating", _TIERS, index=2, key="in_tier", disabled=pending,
                help="Turn on the toggle above to pre-screen without a UMCET result.",
            )
            go = st.button("Evaluate eligibility", type="primary", use_container_width=True)

            st.caption("Or try an example student:")
            ex_cols = st.columns(len(_EXAMPLES))
            for col, name in zip(ex_cols, _EXAMPLES):
                col.button(name, key=f"ex_{name}", on_click=_load_example, args=(name,), use_container_width=True)

        if go:
            vals, errors = {}, {}
            for key, label, raw in (("gwa", "GWA", gwa), ("math", "Math grade", math), ("eng", "English grade", eng)):
                vals[key], err = _parse(label, raw)
                if err:
                    errors[key] = err
            if errors:
                st.session_state.pop("hg_eval", None)
                for msg in errors.values():
                    st.error(msg, icon="⚠️")
            else:
                student = StudentInput(
                    gwa=vals["gwa"], math=vals["math"], english=vals["eng"], shs_track=track,
                    umcet_tier=None if pending else UMCETTier.from_label(tier),
                    umcet_received=not pending,
                )

                # Original rule engine remains responsible for every verdict.
                results = evaluate(student)

                # Added: show skeleton while the AI explains the results.
                loading = st.empty()
                with loading.container():
                    ui.render_skeleton(lines=4, title="Analyzing your results")
                    st.caption(
                        "The eligibility verdict is calculated by the rule engine; "
                        "AI only explains it."
                    )

                text, used_ai = advisor.explain_ex(student, results)

                loading.empty()
                st.session_state["hg_eval"] = dict(
                    student=student, results=results, focus=program, explanation=text, used_ai=used_ai,
                )

    with right:
        data = st.session_state.get("hg_eval")
        if data:
            _results_panel(data)
        else:
            ui.render_state("empty", "Your result will appear here",
                            "Fill in the form and press Evaluate eligibility.")

    with st.expander("How are results calculated?"):
        st.markdown(
            "- Each program has minimum cutoffs for GWA, Math, English and (for degrees) the UMCET rating.\n"
            "- A **rule engine written in plain Python** compares your numbers to those cutoffs. "
            "It decides every verdict and lists exactly which requirement is short.\n"
            "- The **local AI (Ollama)** only explains the result in friendly language. It cannot change it.\n"
            "- If you don't have a UMCET result yet, grade-eligible programs show as *Pending UMCET*."
        )
    ui.render_source_card(
        "Source of the cutoffs",
        "CCIS College Requirements document supplied to this prototype (see the CCIS Programs page). "
        "Treated as demonstration data until verified with UMak.",
    )
    ui.render_footer()
